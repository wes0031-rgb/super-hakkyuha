export const byTag = (tag) => CHUNKS.filter((c) => c.tag === tag);
export const normal = () => CHUNKS.filter((c) => !c.tag);

export function validateChunks() {
  const errs = [];
  for (const c of CHUNKS) {
    if (c.rows.length !== 9) errs.push(`${c.id}: 행 ${c.rows.length}개 (9개여야 함)`);
    c.rows.forEach((r, i) => {
      if (r.length !== CHUNK_COLS) errs.push(`${c.id}: ${i}행 길이 ${r.length}`);
    });
    const ground = c.rows[8] || '';
    let run = 0;
    for (let x = 0; x <= CHUNK_COLS; x++) {
      if (ground[x] === '.') { run++; continue; }
      if (run > 4) errs.push(`${c.id}: 구멍 ${run}칸 (4칸 이하여야 함)`);
      run = 0;
    }
    for (let x = 0; x < CHUNK_COLS; x++) {
      const hang = c.rows.some((r) => r[x] === 'h');
      if (hang && ground[x] === '.') errs.push(`${c.id}: ${x}열 — 매달린 것 아래가 구멍`);
    }
    if (ground[0] !== 'G') errs.push(`${c.id}: 첫 칸이 지면이 아님`);
    if (ground[CHUNK_COLS - 1] !== 'G') errs.push(`${c.id}: 마지막 칸이 지면이 아님`);
  }
  return errs;
}
